import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const webRoot = resolve(import.meta.dirname, "..");
const repositoryRoot = resolve(webRoot, "..");
const outputPath = join(webRoot, "lib", "api.generated.ts");
const tempRoot = mkdtempSync(join(tmpdir(), "whats-a-cv-openapi-"));
const schemaPath = join(tempRoot, "openapi.json");

try {
  const schema = spawnSync(
    "uv",
    [
      "run",
      "--project",
      join(repositoryRoot, "agent"),
      "python",
      "-c",
      'import json; from whats_a_cv.app import app; print(json.dumps(app.openapi()))',
    ],
    {
      cwd: repositoryRoot,
      encoding: "utf8",
      env: {
        ...process.env,
        UV_CACHE_DIR: process.env.UV_CACHE_DIR ?? join(tmpdir(), "whats-a-cv-uv-cache"),
      },
    },
  );

  if (schema.status !== 0) {
    process.stderr.write(schema.stderr);
    process.exit(schema.status ?? 1);
  }

  writeFileSync(schemaPath, schema.stdout);
  const generator = join(webRoot, "node_modules", ".bin", "openapi-typescript");
  const result = spawnSync(generator, [schemaPath, "-o", outputPath], {
    cwd: webRoot,
    encoding: "utf8",
  });

  if (result.status !== 0) {
    process.stderr.write(result.stderr);
    process.exit(result.status ?? 1);
  }

  const generated = readFileSync(outputPath, "utf8");
  writeFileSync(outputPath, `// Generated by npm run generate:api. Do not edit.\n${generated}`);
} finally {
  rmSync(tempRoot, { recursive: true, force: true });
}
